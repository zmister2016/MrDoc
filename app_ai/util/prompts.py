# RAG问答Prompt
def build_answer_prompt(question, sections):
    # context = "\n\n".join([
    #     f"[{i+1}]【{sec['doc_title']}】\n{sec['content']}"
    #     for i, sec in enumerate(sections)
    # ])
    context = "\n\n".join([
        f"【{sec['section_title']}】\n"
        f"路径：{sec['title_path']}\n"
        f"来源：{sec['doc_title']}\n"
        f"{sec['content']}"
        for sec in sections
    ])

    return f"""你是一个知识库问答助手，请根据【参考内容】回答【问题】。

【参考内容】
{context}

【问题】
{question}

【作答要求】
1. 只根据【参考内容】作答，回答中的每个关键信息都必须在参考内容中有依据；参考内容可能来自不同章节，信息互补或重复时可综合多块内容回答；
2. 【冲突识别】如果多个参考片段描述同一实体、职位、事件或事实，但存在不同的人名、数字、时间、届次或结论，必须识别这种冲突；仅措辞不同、精度不同或互为补充的信息不视为冲突；
3. 【冲突消歧】遇到冲突时，应优先依据问题中的明确限定条件进行判断，例如时间、届次、事件名称、会议名称等；不得仅因为某个事实看起来更新、某个文档排名更高或某个说法出现次数更多，就认定其一定正确；
4. 【无法唯一确定】如果现有证据仍无法唯一确定答案，应明确说明存在冲突，并分别列出相关事实及其依据，而不是自行猜测；
5. 【多子问题】对于包含多个子问题的问题，应逐项确认每个子问题都有对应证据后再作答；若任一部分缺少对应证据，明确说明该部分在参考内容中未找到，不得推测补充；
6. 回答前请自查以下事项（内部检查即可，无需在答案中输出检查过程）：是否回答了问题中的每一个子问题？是否遗漏了参考内容中的关键事实？是否存在相互冲突的证据？如果存在冲突，是否已经根据问题限定条件完成消歧？最终答案中的每个关键结论是否都有对应证据？
7. 仅当参考内容与问题完全无关时，回答"未在文档中找到相关内容"；
8. 回答要清晰、简洁；
9. 【图片输出】如果【参考内容】中包含 Markdown 图片语法（形如 ![说明](/media/xxx.png)），且该图片与问题相关，必须把该图片语法**直接插入到回答正文的对应位置**，让图片穿插在相关文字之间一起显示，而不是只用文字描述或提及图片：
   - 图片地址必须与参考内容完全相同，禁止改写、截断、补全域名或自行拼接；
   - 该插图所在段落应配合简短说明文字（例如"如下图所示："），图片紧跟其后；
   - 禁止只写"见图/参考图片 xxx.png/图片地址如下"之类的文字而不输出图片本身，也禁止把图片集中堆到回答末尾；
   - 参考内容中不存在的图片，禁止编造或引用外部图片链接。"""