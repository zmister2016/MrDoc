def build_index_prompt(markdown_content: str) -> str:
    return f"""
你是一个“知识库结构化引擎”。

请对以下 Markdown 文档进行分析，并输出结构化 JSON。

输出格式如下：

{{
  "summary": "文档摘要",
  "sections": [
    {{
      "title": "章节标题",
      "summary": "核心要点总结（必须具体）",
      "keywords": ["用户搜索词"],
      "tags": ["分类标签"],
      "faqs": [
        {{
          "q": "用户真实问题",
          "a": "基于原文的回答",
          "ref": "章节标题"
        }}
      ]
    }}
  ]
}}

【核心强化要求】

一、summary（非常重要）
- 必须是“可回答问题的内容”，而不是概述
- 必须包含具体信息（功能 / 限制 / 数字 / 条件）
- 禁止使用“本文介绍…”、“本节说明…”
- 示例：
  ❌ 介绍了权限管理
  ✅ 支持公开、私密和指定用户三种权限；指定用户最多支持100人

---

二、section.summary（最关键）
- 每一句必须包含“有效信息”（功能 / 限制 / 数据）
- 优先提取：
  - 怎么做
  - 有什么限制
  - 支持什么
- 如果一句话没有信息量 → 删除
- 使用短句 + 分号分隔

---

三、keywords（用于搜索）
- 必须是用户可能搜索的词
- 优先使用：
  - 功能名（权限配置）
  - 动作词（如何设置权限）
  - 场景词（团队协作权限）
- 禁止：
  ❌ ["介绍", "功能"]
  ✅ ["权限设置", "用户权限限制"]

---

四、FAQ（非常关键）
- 必须模拟真实用户问题（口语化）
- 优先生成：
  - 如何类（怎么设置权限？）
  - 限制类（最多支持多少人？）
  - 对比类（公开和私密有什么区别？）
- 回答必须：
  - 简洁
  - 基于原文
  - 包含具体信息

---

五、严格规则
- 不允许编造内容
- 所有信息必须来自原文
- 输出必须是合法 JSON
- 不要输出解释

---

【文档内容】
{markdown_content}
"""

